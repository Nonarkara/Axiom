function updateI18nFile() {
  const i18nPath = path.resolve('axiomx/i18n.js');
  let content = fs.readFileSync(i18nPath, 'utf8');

  // Replace docs block in i18n.js
  const docsJson = JSON.stringify(DOCS_TRANSLATIONS, null, 2);
  const regex = /docs:\s*\{[\s\S]*\}\s*\n\};\s*$/;
  const replacement = `docs: ${docsJson}\n};\n`;

  if (regex.test(content)) {
    content = content.replace(regex, replacement);
  } else {
    // If regex did not match ending, find 'docs:'
    const docsIdx = content.lastIndexOf('docs:');
    if (docsIdx !== -1) {
      content = content.slice(0, docsIdx) + `docs: ${docsJson}\n};\n`;
    }
  }

  fs.writeFileSync(i18nPath, content, 'utf8');
  console.log('Successfully updated docs in axiomx/i18n.js for all languages!');
}

updateI18nFile();
